-- Migração: criar tabela de avaliações de clientes
-- Execute este SQL no Supabase SQL Editor

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  order_id text not null,
  slug text,
  nome text,
  email text,
  estrelas integer not null check (estrelas >= 1 and estrelas <= 5),
  comentario text,
  aprovada boolean default false,
  created_at timestamptz default now()
);

-- Índice para consultas rápidas por ordem e por aprovação
create index if not exists idx_reviews_order_id on public.reviews(order_id);
create index if not exists idx_reviews_aprovada on public.reviews(aprovada) where aprovada = true;
create index if not exists idx_reviews_created_at on public.reviews(created_at desc);

-- Habilitar RLS (Row Level Security)
alter table public.reviews enable row level security;

-- Política: qualquer pessoa pode inserir uma avaliação (sem autenticação)
create policy "reviews_insert_anon" on public.reviews
  for insert with check (true);

-- Política: qualquer pessoa pode ler avaliações aprovadas
create policy "reviews_select_approved" on public.reviews
  for select using (aprovada = true);

-- Política: apenas service role pode ler/atualizar todas (para admin)
create policy "reviews_service_role_all" on public.reviews
  for all using (auth.role() = 'service_role');
